"""
E1 · Эмбеддинг — вектор смысла

Задание: 6 фраз — две пары с одним смыслом и разными словами,
одна пара с общими словами и разным смыслом.
Сначала предсказать близости, потом посчитать.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from chat import read_file_settings
read_file_settings()

import numpy as np
from embed_utils import embed

texts = [
    # Пара 1: один смысл, разные слова
    "Когда можно пересдать экзамен?",                          # 0
    "В какие сроки разрешена повторная аттестация?",           # 1

    # Пара 2: один смысл, разные слова
    "Студент получил неудовлетворительную оценку",            # 2
    "Обучающийся имеет академическую задолженность",          # 3

    # Пара 3: общие слова, разный смысл
    "В столовой новое меню на обед",                           # 4
    "В меню экзаменационной сессии новые предметы",            # 5
]

# --- Предсказание (до запуска) ---
# 0↔1  ≈ 0.75–0.90  (один смысл: пересдача / повторная аттестация)
# 2↔3  ≈ 0.70–0.85  (один смысл: неуд → академ. задолженность)
# 4↔5  ≈ 0.25–0.45  (разный смысл, общее слово «меню»)
# 0↔4  ≈ 0.05–0.25  (не связаны)
# 1↔2  ≈ 0.40–0.60  (частично связаны)

print("Векторизация через OpenRouter (text-embedding-3-small)...")
V = embed(texts)
print(f"shape: {V.shape}")

sim = np.round(V @ V.T, 3)
print("\nМатрица косинусных близостей:")
print(sim)

print("\nФразы:")
for i, t in enumerate(texts):
    print(f"  [{i}] {t}")

print("\n--- Ключевые пары (факт) ---")
pairs = [
    (0, 1, "один смысл"),
    (2, 3, "один смысл"),
    (4, 5, "разный смысл, общие слова"),
    (0, 4, "не связаны"),
    (1, 2, "частично"),
]
for i, j, lab in pairs:
    print(f"  {i}↔{j}: {sim[i, j]:.3f}   ({lab})")

print("\nВывод: «Пересдача» ближе к «повторной аттестации», чем к «столовой»,")
print("хотя общих слов нет. Абсолютные числа зависят от модели — важен порядок.")
