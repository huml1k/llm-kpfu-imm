"""MCP-сервер: search_docs — поиск по положениям КФУ."""
from mcp.server.mcpserver import MCPServer
from search_core import search, format_hits, THRESHOLD

mcp = MCPServer("kfu-docs")

@mcp.tool()
def search_docs(query: str) -> str:
    """
    Ищет фрагменты локальных нормативных актов КФУ по смыслу запроса.
    
    КОГДА ИСПОЛЬЗОВАТЬ:
    - Пользователь спрашивает о правилах, сроках, пересдачах, стипендиях, отчислениях.
    - Нужно проверить факт в официальных документах.
    
    КАК ИСПОЛЬЗОВАТЬ:
    - Формулируй query кратко, используя 2-4 ключевых слова (например: "пересдача экзамена комиссия сроки").
    - Не используй разговорные фразы вроде "подскажи пожалуйста".
    
    ЧТО ВОЗВРАЩАЕТ:
    - Топ-3 наиболее релевантных фрагмента с номерами [1], [2], [3].
    - Эти номера ты ОБЯЗАН указать в поле "sources" своего финального JSON-ответа.
    - Если вернет "Ничего не найдено", сообщи об этом пользователю честно.
    """
    hits = search(query, k=3, threshold=THRESHOLD)
    if not hits:
        return "Ничего не найдено"
    return format_hits(hits)

if __name__ == "__main__":
    mcp.run()